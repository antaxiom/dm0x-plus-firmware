/// Hardware-agnostic Field-Oriented Control (FOC) primitives in fixed-point Q15/i32 math.
/// Designed to run inside the high-priority ADC/PWM interrupt service routine (e.g., 16-20 kHz).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PhaseCurrents {
    pub i_a_ma: i32,
    pub i_b_ma: i32,
    pub i_c_ma: i32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AlphaBeta {
    pub alpha: i32,
    pub beta: i32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DqFrame {
    pub d: i32,
    pub q: i32,
}

/// 3-phase timer compare values (0..=pwm_period) generated by Space Vector PWM.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PhaseDuties {
    pub pwm_a: u16,
    pub pwm_b: u16,
    pub pwm_c: u16,
}

/// Fast fixed-point sine and cosine computation in Q15 (-32767..=32767).
/// `angle` spans the full electrical circle `0..=65535` (`0..2*pi`).
pub const fn sin_cos_q15(angle: u16) -> (i16, i16) {
    let sin = sin_q15(angle);
    let cos = sin_q15(angle.wrapping_add(16384));
    (sin, cos)
}

/// Second-order parabolic sine approximation with fourth-order correction in Q15.
/// Maximum absolute error across [0, 2*pi) is < 0.1% (~30 LSB in Q15).
pub const fn sin_q15(angle: u16) -> i16 {
    let x = angle as i16 as i64;
    let abs_x = if x < 0 { -x } else { x };
    // Base parabola in Q15: y0 = x * (32768 - |x|) / 8192, peaking at 32768
    let y0 = (x * (32768 - abs_x)) >> 13;
    let abs_y0 = if y0 < 0 { -y0 } else { y0 };
    // Fourth-order correction: y = y0 + 0.225 * y0 * (|y0| - 1)
    // where 0.225 in Q15 is 7373 / 32768
    let corr = (((y0 * (abs_y0 - 32768)) >> 15) * 7373) >> 15;
    let y = y0 + corr;
    if y > 32767 {
        32767
    } else if y < -32767 {
        -32767
    } else {
        y as i16
    }
}

/// Clarke transform: converts 3-phase currents (Ia, Ib, Ic) into 2-axis stationary frame (alpha, beta).
/// Uses 1/sqrt(3) ~= 18919 / 32768 (Q15).
pub const fn clarke_transform(currents: PhaseCurrents) -> AlphaBeta {
    let alpha = currents.i_a_ma;
    // beta = (i_a + 2 * i_b) / sqrt(3)
    let num = currents.i_a_ma + 2 * currents.i_b_ma;
    let beta = ((num as i64 * 18919) >> 15) as i32;
    AlphaBeta { alpha, beta }
}

/// Park transform: rotates stationary (alpha, beta) into synchronous rotor frame (d, q).
/// `sin_theta_q15` and `cos_theta_q15` are in Q15 (-32768..=32767).
pub const fn park_transform(ab: AlphaBeta, sin_theta_q15: i16, cos_theta_q15: i16) -> DqFrame {
    let sin = sin_theta_q15 as i64;
    let cos = cos_theta_q15 as i64;
    let alpha = ab.alpha as i64;
    let beta = ab.beta as i64;

    let d = ((alpha * cos + beta * sin) >> 15) as i32;
    let q = ((beta * cos - alpha * sin) >> 15) as i32;
    DqFrame { d, q }
}

/// Inverse Park transform: rotates synchronous (d, q) voltage command back to stationary (alpha, beta).
pub const fn inverse_park_transform(
    vq_vd: DqFrame,
    sin_theta_q15: i16,
    cos_theta_q15: i16,
) -> AlphaBeta {
    let sin = sin_theta_q15 as i64;
    let cos = cos_theta_q15 as i64;
    let d = vq_vd.d as i64;
    let q = vq_vd.q as i64;

    let alpha = ((d * cos - q * sin) >> 15) as i32;
    let beta = ((d * sin + q * cos) >> 15) as i32;
    AlphaBeta { alpha, beta }
}

/// 7-segment Space Vector PWM (SVPWM) via min-max common-mode neutral-point injection.
/// Takes stationary voltage vector `v_ab` in Q15 (-32767..=32767) and `pwm_period` timer counts.
pub fn compute_svpwm(v_ab: AlphaBeta, pwm_period: u16) -> PhaseDuties {
    // Inverse Clarke to obtain 3-phase reference voltages (Va, Vb, Vc) in Q15
    // sqrt(3)/2 ~= 28378 / 32768 (Q15)
    let v_a = v_ab.alpha;
    let half_alpha = v_ab.alpha / 2;
    let sqrt3_half_beta = ((v_ab.beta as i64 * 28378) >> 15) as i32;

    let v_b = -half_alpha + sqrt3_half_beta;
    let v_c = -half_alpha - sqrt3_half_beta;

    // Min-max neutral-point shift (saddle wave) for maximum DC bus utilization
    let v_min = v_a.min(v_b).min(v_c);
    let v_max = v_a.max(v_b).max(v_c);
    let v_offset = (v_min + v_max) / 2;

    let map_duty = |v_phase: i32| -> u16 {
        let shifted = (v_phase - v_offset).clamp(-32768, 32767);
        // Map [-32768, 32768] -> [0, pwm_period]
        let num = (shifted + 32768) as i64 * (pwm_period as i64);
        (num >> 16).clamp(0, pwm_period as i64) as u16
    };

    PhaseDuties {
        pwm_a: map_duty(v_a),
        pwm_b: map_duty(v_b),
        pwm_c: map_duty(v_c),
    }
}

/// Discrete PI controller with anti-windup clamping for Id and Iq current loops.
#[derive(Debug, Clone)]
pub struct PiController {
    pub kp_q10: i32,
    pub ki_q10: i32,
    pub integral: i64,
    pub out_min: i32,
    pub out_max: i32,
}

impl PiController {
    pub const fn new(kp_q10: i32, ki_q10: i32, out_min: i32, out_max: i32) -> Self {
        Self {
            kp_q10,
            ki_q10,
            integral: 0,
            out_min,
            out_max,
        }
    }

    pub fn reset(&mut self) {
        self.integral = 0;
    }

    pub fn step(&mut self, target: i32, measured: i32) -> i32 {
        let error = (target - measured) as i64;
        let p_term = (error * self.kp_q10 as i64) >> 10;

        self.integral += (error * self.ki_q10 as i64) >> 10;
        let min_i = (self.out_min as i64) << 4;
        let max_i = (self.out_max as i64) << 4;
        self.integral = self.integral.clamp(min_i, max_i);

        let total = p_term + (self.integral >> 4);
        total.clamp(self.out_min as i64, self.out_max as i64) as i32
    }
}

/// Decodes 3-bit Hall sensor states (`1..=6`) into electrical angle `0..=65535`
/// with configurable `angle_offset` (matching Display Settings > Motor > AngleOffset).
pub const fn decode_hall_angle(hall_bits: u8, angle_offset: u16) -> Option<u16> {
    let base_angle: u16 = match hall_bits & 0b111 {
        0b001 => 0,     // 0 deg
        0b011 => 10922, // 60 deg
        0b010 => 21845, // 120 deg
        0b110 => 32768, // 180 deg
        0b100 => 43690, // 240 deg
        0b101 => 54613, // 300 deg
        _ => return None,
    };
    Some(base_angle.wrapping_add(angle_offset))
}

/// Complete hard real-time FOC current regulator executing at PWM frequency.
pub struct FocCurrentLoop {
    pub id_pi: PiController,
    pub iq_pi: PiController,
    pub pwm_period: u16,
}

impl FocCurrentLoop {
    pub const fn new(pwm_period: u16) -> Self {
        Self {
            id_pi: PiController::new(512, 64, -30_000, 30_000),
            iq_pi: PiController::new(512, 64, -30_000, 30_000),
            pwm_period,
        }
    }

    /// Executes one deterministic FOC current-loop iteration from measured phase currents,
    /// electrical angle (`0..=65535`), and target `id_target_ma` / `iq_target_ma`.
    pub fn step_isr(
        &mut self,
        currents: PhaseCurrents,
        electrical_angle: u16,
        id_target_ma: i32,
        iq_target_ma: i32,
    ) -> PhaseDuties {
        let ab_curr = clarke_transform(currents);
        let (sin_t, cos_t) = sin_cos_q15(electrical_angle);
        let dq_curr = park_transform(ab_curr, sin_t, cos_t);

        let v_d = self.id_pi.step(id_target_ma, dq_curr.d);
        let v_q = self.iq_pi.step(iq_target_ma, dq_curr.q);

        let v_ab = inverse_park_transform(DqFrame { d: v_d, q: v_q }, sin_t, cos_t);
        compute_svpwm(v_ab, self.pwm_period)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_zero_voltage_gives_50_percent_svpwm_duties() {
        let duties = compute_svpwm(AlphaBeta { alpha: 0, beta: 0 }, 2000);
        assert_eq!(duties.pwm_a, 1000);
        assert_eq!(duties.pwm_b, 1000);
        assert_eq!(duties.pwm_c, 1000);
    }

    #[test]
    fn test_park_and_inverse_park_roundtrip() {
        let orig = AlphaBeta {
            alpha: 12_000,
            beta: -5_000,
        };
        let (sin_t, cos_t) = sin_cos_q15(10_922); // ~60 degrees
        let dq = park_transform(orig, sin_t, cos_t);
        let recovered = inverse_park_transform(dq, sin_t, cos_t);

        // Within 0.2% of full scale (12000 mA) for Q15 fixed-point parabolic trig
        assert!((orig.alpha - recovered.alpha).abs() <= 25);
        assert!((orig.beta - recovered.beta).abs() <= 25);
    }
}
